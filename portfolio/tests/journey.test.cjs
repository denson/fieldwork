assert.ok(note.includes('could still use seismic information'));
assert.ok(note.includes('step=readiness'));
assert.ok(note.includes('Flat-map prediction for each 1,000 km route'));
assert.equal(J.surveyNote(s,base),null);
assert.equal(J.surveyMinutes(J.surveyBaseline),'84.1');
assert.equal(J.surveyTime(2000)>J.surveyBaseline,true);
assert.equal(J.surveyTime(6000)<J.surveyBaseline,true);
assert.equal(J.surveyReady(s.survey),false);
const arrivalCases=[
  ['flat',false,false],['ridge',true,false],['trough',false,true],['both',true,true]
];
for(const [id,eastFits,westFits] of arrivalCases){
  const fit=J.surveyFit(J.surveyScenarios[id]);
  assert.equal(Math.abs(fit.east)<.05,eastFits,id+' east');
  assert.equal(Math.abs(fit.west)<.05,westFits,id+' west');
}
Object.assign(s.survey,{...J.surveyScenarios.both,scenario:'both',prediction:'both',revealed:true});
s.text.surveyInsight='The east arrival was later and the west arrival was earlier.';
note=J.checkpoint(s,base);
assert.ok(note.includes('My explanation before reveal: A ridge east and a trough west'));
assert.ok(note.includes('east 2,000 m; west 6,000 m'));
assert.ok(note.includes(s.text.surveyInsight));
assert.ok(note.includes('not a measurement of the selected historical event'));
const survey=J.surveyNote(s,base);
assert.ok(survey.includes('My two-route arrival-time investigation'));
assert.ok(survey.includes('east 2,000 m; west 6,000 m'));
assert.ok(survey.includes('What I noticed')===false);
assert.ok(survey.includes('step=reach'));
assert.ok(!survey.includes('## Fixed checks'));
assert.ok(!note.includes('undefined')&&!note.includes('plan='));
assert.equal(new URL(J.url(base,s)).pathname,'/portfolio/');
assert.equal(new URL(J.url(base,s)).searchParams.get('case'),'alaska1964');
assert.equal(new URL(J.url(base,s)).hash,'');
const dedicated='https://denson.github.io/fieldwork/tsunami.html';
assert.equal(new URL(J.url(dedicated,s)).pathname,'/fieldwork/tsunami.html');
assert.equal(new URL(J.url(dedicated,s)).searchParams.has('demo'),false);
assert.equal(J.entry(null,new URLSearchParams('case=japan2011&step=missing'),true).step,'missing');

s.text.maintenancePower='Keep sensors powered.';
s.text.maintenancePeople='Prepare accessible evacuation plans.';
s.job='people';note=J.checkpoint(s,base);
